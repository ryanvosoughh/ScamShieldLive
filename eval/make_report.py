"""Phase 4D: write eval/results.md from eval/results.json, and the timing files if they are there.

    .venv/bin/python eval/make_report.py

No model calls, so the report can be rebuilt any time for free. results.md is
generated: to change it, change this script or rerun the evaluation, not the file.
"""
from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
RESULTS_FILE = EVAL_DIR / "results.json"
TIMING_FILE = EVAL_DIR / "timing.json"
BASELINE_TIMING_FILE = EVAL_DIR / "timing_baseline.json"  # the run that found the pacing bug
REPORT_FILE = EVAL_DIR / "results.md"
FAILURE_ANALYSIS = EVAL_DIR / "failure_analysis.md"

WARNED = ("yellow", "red")
RED_ONLY = ("red",)


def rates(results: list[dict], warned_levels: tuple[str, ...]) -> dict[str, tuple[int, int]]:
    """Recall, precision and false-alarm rate, as (part, whole), when "warned" means these levels."""
    counted = [result for result in results if result["outcome"] != "unknown"]
    scams = [result for result in counted if result["label"] == "scam"]
    normals = [result for result in counted if result["label"] == "normal"]
    caught = sum(result["level"] in warned_levels for result in scams)
    false_alarms = sum(result["level"] in warned_levels for result in normals)
    return {
        "recall": (caught, len(scams)),
        "precision": (caught, caught + false_alarms),
        "false_alarm_rate": (false_alarms, len(normals)),
    }


def percent(part_whole: tuple[int, int]) -> str:
    part, whole = part_whole
    return f"{100 * part / whole:.0f}% ({part}/{whole})" if whole else "n/a (0/0)"


def by_tag(results: list[dict]) -> list[tuple[str, int, int, int]]:
    """(tag, cases, right, wrong) for every tag, most common first."""
    rows = []
    for tag, cases in Counter(tag for result in results for tag in result["tags"]).items():
        tagged = [result for result in results if tag in result["tags"]]
        right = sum(result["outcome"] in ("caught", "correct") for result in tagged)
        wrong = sum(result["outcome"] in ("missed", "false_alarm") for result in tagged)
        rows.append((tag, cases, right, wrong))
    return sorted(rows, key=lambda row: (-row[1], row[0]))


def seconds(value: float | None) -> str:
    return "never" if value is None else f"{value:.1f} s"


def gap(after: float | None, before: float | None) -> str:
    """How long after the script's marker the meter changed."""
    if after is None or before is None:
        return "–"
    difference = after - before
    return f"{difference:+.1f} s" if difference >= 0 else f"{-difference:.1f} s before it"


def timing_table(timing: dict) -> list[str]:
    """One timing run as a table, with the pacing and code it ran with."""
    run = timing["run"]
    pacing = f"checks at least {run['check_interval_seconds']:g} s apart"
    if run.get("checks_per_minute"):  # only the run from before the pacing fix had a cap
        pacing += f" and at most {run['checks_per_minute']} a minute"
    rows = [
        f"Run at {run['run_at']}: {pacing}, prompt `{run['prompt_sha256']}`, code `{run['git_commit']}`.",
        "",
        "| Call | Kind | Ends at | Last check | Warning sign | First warning | Ask | First red |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for call in timing["calls"]:
        last = call["states"][-1]["at"] if call["states"] else None
        rows.append(
            f"| {call['title']} | {call['kind']} | {seconds(call['seconds'])} | {seconds(last)} |"
            f" {seconds(call['warning_sign_at']) if call['warning_sign_at'] else '–'} |"
            f" {seconds(call['first_warning_at'])} ({gap(call['first_warning_at'], call['warning_sign_at'])}) |"
            f" {seconds(call['ask_at']) if call['ask_at'] else '–'} |"
            f" {seconds(call['first_red_at'])} ({gap(call['first_red_at'], call['ask_at'])}) |"
        )
    failed = sum(call["failed_checks"] for call in timing["calls"])
    rows += ["", f"{sum(call['checks'] for call in timing['calls'])} checks in all, {failed} failed."]
    return rows


def build_report(report: dict, timing: dict | None, baseline: dict | None = None) -> str:
    run, results = report["run"], report["results"]
    count = Counter(result["outcome"] for result in results)
    scams = sum(result["label"] == "scam" for result in results)
    normals = len(results) - scams
    times = [result["seconds"] for result in results if result["outcome"] != "unknown"]
    out = [
        "# Evaluation results",
        "",
        "Generated by `eval/make_report.py` from `results.json` and `timing.json`. Don't edit it by hand:",
        "rerun the evaluation or the script. How the cases were made, and their limits, is in `README.md`.",
        "",
        f"**A smoke test:** {len(results)} short text calls ({scams} scams, {normals} normal), none of them used",
        "while tuning the prompt. With so few cases, one case moves a rate by several points.",
        "",
        "## Run",
        "",
        "| Run at (UTC) | Model | Yellow / red line | Prompt | Cases | Code |",
        "|---|---|---|---|---|---|",
        f"| {run['run_at']} | `{run['model']}` | {run['yellow_threshold']} / {run['red_threshold']} |"
        f" `{run['prompt_sha256']}` | `{run['cases_sha256']}` | `{run['git_commit']}` |",
        "",
        "## Headline",
        "",
        f"- **Scams caught:** {count['caught']} of {scams}",
        f"- **Normal calls left green:** {count['correct']} of {normals}",
    ]
    if count["unknown"]:
        out.append(f"- **No verdict:** {count['unknown']} (the check kept failing; not counted either way)")
    if times:
        out.append(f"- **Time per check:** {statistics.mean(times):.1f} s on average, {max(times):.1f} s at worst")
    out += [
        "",
        "## Confusion matrix",
        "",
        "| | Warned (yellow or red) | Not warned (green) |",
        "|---|---|---|",
        f"| **Scam** | {count['caught']} caught | {count['missed']} missed |",
        f"| **Normal** | {count['false_alarm']} false alarm{'' if count['false_alarm'] == 1 else 's'} |"
        f" {count['correct']} correct |",
        "",
        "## Recall, precision and false alarms",
        "",
        "Recall: of the scams, how many warned. Precision: of the warnings, how many were scams.",
        "",
        "| Counted as a warning | Recall | Precision | False-alarm rate |",
        "|---|---|---|---|",
    ]
    for name, levels in (("Yellow or red", WARNED), ("Red only", RED_ONLY)):
        rate = rates(results, levels)
        out.append(
            f"| {name} | {percent(rate['recall'])} | {percent(rate['precision'])} | {percent(rate['false_alarm_rate'])} |"
        )
    out += ["", "## By tag", "", "| Tag | Cases | Right | Wrong |", "|---|---|---|---|"]
    out += [f"| `{tag}` | {cases} | {right} | {wrong} |" for tag, cases, right, wrong in by_tag(results)]

    if timing:
        out += [
            "",
            "## Time to first warning (the demo calls)",
            "",
            "Each demo call played in real time through the live pipeline: the same `CallSession`, with the",
            "real check on Groq. The *warning sign* is the first line the script rates yellow or above; the",
            "*ask* is the first line with a red flag. The gaps say how long after each one the meter changed.",
            "",
            *timing_table(timing),
        ]
        if baseline:
            out += [
                "",
                "### Before the pacing fix",
                "",
                "The first timing run, kept in `timing_baseline.json`. Checks could come every 4 s but at most",
                "5 a minute, and all 5 were used up on the small talk, so nothing was checked when the scam was",
                "asked for. The 24 single-check cases above couldn't show this.",
                "",
                *timing_table(baseline),
            ]

    out += [
        "",
        "## Every case",
        "",
        "| Case | Label | Meter | Model risk | Red flags | Outcome | Time |",
        "|---|---|---|---|---|---|---|",
    ]
    for result in results:
        risk = "–" if result["risk"] is None else result["risk"]
        flags = ", ".join(result["red_flags"]) or "–"
        out.append(
            f"| `{result['id']}` | {result['label']} | {result['level']} | {risk} | {flags} |"
            f" {result['outcome'].replace('_', ' ')} | {result['seconds']:.1f} s |"
        )

    mistakes = [result for result in results if result["outcome"] in ("missed", "false_alarm")]
    # A scam the model scored under the red line, so it was red only because of a red flag, or only yellow.
    near_misses = [
        result
        for result in results
        if result["outcome"] == "caught" and result["risk"] is not None and result["risk"] < run["red_threshold"]
    ]
    out += ["", "## Mistakes and near misses", ""]
    for result in mistakes:
        out.append(
            f"- **`{result['id']}`, {result['outcome'].replace('_', ' ')}:** the meter showed {result['level']}"
            f" (model risk {result['risk']}, red flags: {', '.join(result['red_flags']) or 'none'})."
            f" The model's reason: \"{result['reason']}\""
        )
    for result in near_misses:
        why = "a red flag made it red" if result["level"] == "red" else "it only reached yellow"
        out.append(
            f"- **`{result['id']}`, near miss:** caught, but the model's risk was {result['risk']},"
            f" under the red line of {run['red_threshold']}; {why}"
            f" ({', '.join(result['red_flags']) or 'no red flags'})."
        )
    if not mistakes and not near_misses:
        out.append("None.")
    if FAILURE_ANALYSIS.exists():
        out += ["", f"Why each one happened, and what would fix it: `{FAILURE_ANALYSIS.name}`."]
    return "\n".join(out) + "\n"


def main() -> int:
    if not RESULTS_FILE.exists():
        print("No eval/results.json yet. Run eval/run_eval.py first.", file=sys.stderr)
        return 1
    report = json.loads(RESULTS_FILE.read_text())
    timing = json.loads(TIMING_FILE.read_text()) if TIMING_FILE.exists() else None
    baseline = json.loads(BASELINE_TIMING_FILE.read_text()) if BASELINE_TIMING_FILE.exists() else None
    REPORT_FILE.write_text(build_report(report, timing, baseline))
    print(f"Wrote {REPORT_FILE.relative_to(EVAL_DIR.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
